-- Relative weights, not direct percentages. Shiny is half the same species' normal.
-- Records unsupported species without creating or activating any crate reward.
CREATE TABLE crate_species_weights (
 species VARCHAR(50) PRIMARY KEY,
 rarity VARCHAR(20) NOT NULL CHECK(rarity IN ('easy','intermediate','hard','very_hard')),
 normal_weight NUMERIC(6,3) NOT NULL CHECK(normal_weight>0)
);
