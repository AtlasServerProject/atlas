UPDATE crate_rewards r SET chance=(
 SELECT coalesce((SELECT normal_weight FROM crate_species_weights WHERE species=split_part(r.reward_identifier,' ',1)),1)
) * CASE WHEN r.reward_identifier ~ '(^| )shiny=true( |$)' THEN 0.5 ELSE 1 END
WHERE r.reward_type='POKEMON' AND r.chance>0 AND r.crate_id IN (
 SELECT id FROM crates WHERE identifier IN ('generation_1','generation_2','generation_3','generation_4','generation_5','generation_6','generation_7','generation_8','generation_9','legendary_monthly')
);
