-- Atlas-owned shop data. Prices are starter values in in-game CobbleDollars, editable.
CREATE TABLE npc_shop_offers (
 shop_id VARCHAR(30) NOT NULL,
 item_id VARCHAR(120) NOT NULL,
 buy_price BIGINT NOT NULL CHECK(buy_price BETWEEN 1 AND 1000000000),
 sell_price BIGINT NOT NULL CHECK(sell_price >= 0 AND sell_price < buy_price),
 stock_chance DOUBLE PRECISION NOT NULL DEFAULT 1 CHECK(stock_chance>0 AND stock_chance<=1),
 price_variation INTEGER NOT NULL DEFAULT 0 CHECK(price_variation BETWEEN 0 AND 10),
 sort_order INTEGER NOT NULL DEFAULT 0,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 PRIMARY KEY(shop_id,item_id)
);
CREATE TABLE npc_shop_transactions (
 id UUID PRIMARY KEY,
 player_uuid UUID NOT NULL,
 shop_id VARCHAR(30) NOT NULL,
 item_id VARCHAR(120) NOT NULL,
 direction VARCHAR(4) NOT NULL CHECK(direction IN ('BUY','SELL')),
 quantity INTEGER NOT NULL CHECK(quantity BETWEEN 1 AND 64),
 total BIGINT NOT NULL CHECK(total>0),
 state VARCHAR(12) NOT NULL CHECK(state IN ('PREPARED','APPLYING','COMPLETED','CANCELLED','REVIEW')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX npc_shop_pending_player ON npc_shop_transactions(player_uuid) WHERE state IN ('PREPARED','APPLYING','REVIEW');
