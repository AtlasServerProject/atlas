CREATE TABLE crate_monthly_candidates(species VARCHAR(50) PRIMARY KEY);
CREATE TABLE crate_monthly_periods(period DATE PRIMARY KEY);
CREATE TABLE crate_monthly_selection(
 period DATE NOT NULL REFERENCES crate_monthly_periods(period),
 slot INTEGER NOT NULL CHECK(slot BETWEEN 1 AND 10),species VARCHAR(50) NOT NULL,
 PRIMARY KEY(period,slot),UNIQUE(period,species)
);
ALTER TABLE crate_settings ADD COLUMN monthly_period DATE;
ALTER TABLE crate_deliveries ADD COLUMN rotation_period DATE;
